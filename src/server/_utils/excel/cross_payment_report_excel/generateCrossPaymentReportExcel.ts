import ExcelJS from "exceljs";
import { currentTime, formatDate } from "~/utils/localDateString";
import { DOLLAR_SIGN_NUMBER_FORMAT, QUANTITY_NUMBER_FORMAT, TABLE_HEADER_ROW, TEXT_FORMAT } from "../config";
import type { CrossPayReport } from "~/server/api/routers/reports/_types/crossPayReport";

const TABLE_COLUMN_COUNT = 18;

const tableColumns = [
    { key: "cross_payment_ref", width: 28 },
    { key: "cross_payment_date", width: 18 },
    { key: "buyer_name", width: 28 },
    { key: "payment_term", width: 18 },
    { key: "factory_name", width: 28 },
    { key: "invoice_no", width: 20 },
    { key: "invoice_date", width: 18 },
    { key: "factory_invoice_quantity", width: 18 },
    { key: "factory_invoice_value", width: 18 },
    { key: "factory_payable_value", width: 18 },
    { key: "factory_payment_no", width: 20 },
    { key: "factory_payment_date", width: 18 },
    { key: "fdbc_no", width: 20 },
    { key: "realization_date", width: 18 },
    { key: "rdl_invoice_no", width: 20 },
    { key: "rdl_invoice_date", width: 18 },
    { key: "rdl_invoice_quantity", width: 18 },
    { key: "rdl_invoice_value", width: 18 },
    { key: "regularization_date", width: 18 },
]

const tableHeader = [
    'Cross Payment Reference',
    'Cross Payment Date',
    'Buyer Name',
    'Payment Term',
    'Factory Name',
    'Factory Invoice',
    'Factory invoice Date',
    'Factory Invoice Quantity',
    'Factory Invoice Value',
    'Factory Payable Value',
    'Factory Payment No',
    'Factory Payment Date',
    'FDBC No',
    'Proceed Date',
    'Company invoice',
    'Company invoice Date',
    'Company Invoice Quantity',
    'Company Invoice Value',
    'Regularized Date'
]

type Props = {
    rows: CrossPayReport[];
    cross_pay_from: string | undefined;
    cross_pay_to: string | undefined;
    factory_pay_from: string | undefined;
    factory_pay_to: string | undefined;
    generatedBy: string;
};

export const generateCrossPaymentReportExcel = async (props: Props) => {
    const { rows, cross_pay_from, cross_pay_to, factory_pay_from, factory_pay_to, generatedBy } = props;

    const isCrossPayFilterActive = cross_pay_from && cross_pay_to;
    const isFactoryPayFilterActive = factory_pay_from && factory_pay_to;

    const workbook = new ExcelJS.Workbook();

    // Set file metadata
    workbook.creator = generatedBy; 
    workbook.created = new Date();
    workbook.company = "Nex-Sourcify";
    workbook.subject = "Post-Exfactory Commercial Activity Report";
    workbook.title = "Post-Exfactory Commercial Activity Report";
    workbook.category = "Commercial Reports";
    workbook.manager = "Nexus ERP";

    const worksheet = workbook.addWorksheet("Commission Report", {
        views: [
            {
                state: "frozen",
                ySplit: TABLE_HEADER_ROW,
            },
        ],
    });

    worksheet.columns = tableColumns;

    worksheet.mergeCells(1, 1, 1, 6);
    worksheet.mergeCells(2, 1, 2, 6);
    worksheet.mergeCells(3, 1, 3, 2);
    worksheet.mergeCells(4, 1, 4, 2);
    worksheet.mergeCells(5, 1, 5, 2);

    worksheet.getCell("A1").value = `Cross Payment Report`;

    let dateString = '';

    if(isCrossPayFilterActive){
        dateString = `Cross Payment Date Range: ${formatDate(cross_pay_from)} to ${formatDate(cross_pay_to)}`;
    }
    
    if(isFactoryPayFilterActive) {
       dateString += ` | Factory Payment Date Range: ${formatDate(factory_pay_from)} to ${formatDate(factory_pay_to)}`;
    }

    worksheet.getCell("A2").value = dateString;
    worksheet.getCell("A3").value = `Generated by: ${generatedBy}`;
    worksheet.getCell("A4").value = `Generated on: ${formatDate(new Date())} at ${currentTime}`;

    worksheet.getRow(1).font = {
        bold: true,
        size: 22,
        color: { argb: "FF1F1F1F" },
    };

    worksheet.getRow(2).font = {
        size: 11,
        color: { argb: "FF4B4B4B" },
    };

    worksheet.getRow(3).font = {
        size: 11,
        color: { argb: "FF4B4B4B" },
    };

    worksheet.getRow(4).font = {
        size: 11,
        color: { argb: "FF4B4B4B" },
    };

    worksheet.getRow(6).font = {
        bold: true,
        color: { argb: "FFFFFFFF" },
    };
    
    worksheet.getRow(6).fill = {
        type: "pattern",
        pattern: "solid",
        fgColor: { argb: "1F4E78" },
    };

    worksheet.getRow(TABLE_HEADER_ROW).values = [...tableHeader];
    
    worksheet.autoFilter = {
        from: "A6",
        to: "AC6",
    };

    worksheet.getRow(1).height = 22;
    worksheet.getRow(2).height = 18;
    worksheet.getRow(3).height = 18;
    worksheet.getRow(6).height = 20;

    rows.forEach((row) => worksheet.addRow(row));
    
    // Remove borders from the first 4 rows and all columns
    for (let row = 1; row <= 5; row++) {
        for (let col = 1; col <= TABLE_COLUMN_COUNT; col++) {
            const cell = worksheet.getCell(row, col);
            cell.fill = {
                type: "pattern",
                pattern: "solid",
                fgColor: { argb: "FFFFFF" },
            };
        }
    }

    // Quantity columns
    ["H", "Q"].forEach((col) => {
        worksheet.getColumn(col).numFmt = QUANTITY_NUMBER_FORMAT;
    });

    // Currency columns
    ["I", "J", "R"].forEach((col) => {
        worksheet.getColumn(col).numFmt = DOLLAR_SIGN_NUMBER_FORMAT;
    });

    ["A", "B", "C", "D", "E", "F", "G", "K", "L", "M", "N", "O", "P", "R"].forEach((col) => {
        worksheet.getColumn(col).numFmt = TEXT_FORMAT;
    });

    const totalCommissionRow = worksheet.addRow({
        cross_payment_ref: "Total",
        factory_invoice_quantity: { formula: `SUBTOTAL(109,H${TABLE_HEADER_ROW + 1}:H${worksheet.rowCount})` },
        factory_invoice_value: { formula: `SUBTOTAL(109,I${TABLE_HEADER_ROW + 1}:I${worksheet.rowCount})` },
        factory_payable: { formula: `SUBTOTAL(109,J${TABLE_HEADER_ROW + 1}:J${worksheet.rowCount})` },
        rdl_invoice_quantity: { formula: `SUBTOTAL(109,Q${TABLE_HEADER_ROW + 1}:Q${worksheet.rowCount})` },
        rdl_invoice_value: { formula: `SUBTOTAL(109,R${TABLE_HEADER_ROW + 1}:R${worksheet.rowCount})` },
    });

    totalCommissionRow.font = {
        bold: true,
    };

    worksheet.eachRow((row) => {
        row.alignment = {
            vertical: "middle",
            wrapText: false,
        };
    });

    return await workbook.xlsx.writeBuffer();
};