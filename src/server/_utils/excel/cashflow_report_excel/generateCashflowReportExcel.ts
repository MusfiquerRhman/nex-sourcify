import ExcelJS from "exceljs";
import { currentTime, formatDate } from "~/utils/localDateString";
import { QUANTITY_NUMBER_FORMAT, TABLE_HEADER_ROW, TEXT_FORMAT } from "../config";
import type { CashflowReport } from "~/server/api/routers/reports/_types/cashflowReport";
import { addCashflowCharts } from "./utils/addCashflowCharts";

const REVENUE_NUMBER_FORMAT = '_("$"* #,##0.00_);_("$"* (#,##0.00);_("$"* 0.00_);_(@_)';

const tableColumns = [
    { key: "buyer_name", width: 24 },
    { key: "ci_no", width: 32 },
    { key: "invoice_date", width: 18 },
    { key: "total_ci", width: 20 },
    { key: "calc_shipment_date", width: 24 },
    { key: "term_days", width: 20 },
    { key: "buffer_days", width: 18 },
    { key: "calc_remit_date", width: 22 },
    { key: "remit_week", width: 18 },
    { key: "remit_month", width: 18 },
    { key: "days_overdue", width: 18 },
    { key: "aging_slab", width: 24 },
];

const tableHeader = [
    "Buyer Name",
    "CI No.",
    "CI Date",
    "Revenue",
    "Calculated Shipment Date",
    "Payment Terms",
    "Buffer Days",
    "Calculated Remit Date",
    "Remit Week",
    "Remit Month",
    "Overdue Days",
    "Aging Slab",
];

const agingSlabs = ["Not Overdue", "Less than 30 Days", "Over 30 Days", "Over 60 Days", "Over 90 Days", "Over 120 Days"];

type Props = {
    rows: CashflowReport[];
    fromDate?: string;
    toDate?: string;
    generatedBy: string;
};

type RevenueCriterion = {
    column: "A" | "I" | "J" | "L";
    field: "buyer_name" | "remit_week" | "remit_month" | "aging_slab";
    value: string;
};

export const generateCashflowReportExcel = async (props: Props) => {
    const { rows, fromDate, toDate, generatedBy } = props;

    let dateRange = "All dates";
    if (fromDate && toDate) dateRange = `${formatDate(fromDate)} - ${formatDate(toDate)}`;
    else if (fromDate) dateRange = `From ${formatDate(fromDate)}`;
    else if (toDate) dateRange = `Through ${formatDate(toDate)}`;

    const workbook = new ExcelJS.Workbook();
    workbook.creator = generatedBy;
    workbook.created = new Date();
    workbook.company = "Nex-Sourcify";
    workbook.subject = "Cash Flow Projection";
    workbook.title = "Cash Flow Projection";
    workbook.category = "Accounting Reports";
    workbook.manager = "Nexus ERP";
    workbook.calcProperties.fullCalcOnLoad = true;

    const createWorksheet = (name: string, title: string, columns: { key: string; width: number }[], headers: string[]) => {
        const worksheet = workbook.addWorksheet(name, {
            views: [{ state: "frozen", ySplit: TABLE_HEADER_ROW }],
        });
        worksheet.columns = columns;

        // Keep the same title, metadata, and table layout as the existing Excel reports.
        for (let row = 1; row <= 4; row++) {
            worksheet.mergeCells(row, 1, row, 4);
        }

        worksheet.getCell("A1").value = title;
        worksheet.getCell("A2").value = `Generated by: ${generatedBy}`;
        worksheet.getCell("A3").value = `Generated on: ${formatDate(new Date())} at ${currentTime}`;
        worksheet.getCell("A4").value = `Date Range: ${dateRange}`;
        worksheet.getRow(1).font = { bold: true, size: 22, color: { argb: "FF1F1F1F" } };
        worksheet.getRow(1).height = 30;

        for (let row = 2; row <= 4; row++) {
            worksheet.getRow(row).font = { 
                size: 11, 
                color: { argb: "FF4B4B4B" } 
            };
            worksheet.getRow(row).height = 18;
        }

        for (let row = 1; row < TABLE_HEADER_ROW; row++) {
            for (let column = 1; column <= 26; column++) {
                worksheet.getCell(row, column).fill = { 
                    type: "pattern", 
                    pattern: "solid", 
                    fgColor: { argb: "FFFFFFFF" } 
                };
            }
        }

        const header = worksheet.getRow(TABLE_HEADER_ROW);
        header.values = headers;
        headers.forEach((_, index) => {
            const cell = header.getCell(index + 1);
            cell.font = { bold: true, color: { argb: "FFFFFFFF" } };
            cell.fill = {
                type: "pattern",
                pattern: "solid",
                fgColor: { argb: "FF1F4E78" },
            };
        });

        header.height = 32;

        return worksheet;
    };

    const detail = createWorksheet("CF Aging Details", "CI WISE CASH-FLOW AND AGING INFO", tableColumns, tableHeader);
    detail.properties.tabColor = { argb: "FF4472C4" };
    detail.views = [{ state: "frozen", xSplit: 2, ySplit: TABLE_HEADER_ROW }];
    rows.forEach((row) => detail.addRow(row));

    ["C", "E", "H"].forEach((column) => { detail.getColumn(column).numFmt = "dd-mmm-yyyy"; });
    ["D"].forEach((column) => { detail.getColumn(column).numFmt = REVENUE_NUMBER_FORMAT; });
    ["F", "G", "K"].forEach((column) => { detail.getColumn(column).numFmt = QUANTITY_NUMBER_FORMAT; });
    ["A", "B", "I", "J", "L"].forEach((column) => { detail.getColumn(column).numFmt = TEXT_FORMAT; });

    const firstDataRow = TABLE_HEADER_ROW + 1;
    const lastDataRow = TABLE_HEADER_ROW + rows.length;
    const totalRevenue = rows.reduce((total, row) => total + Math.round((row.total_ci ?? 0) * 100), 0) / 100;

    const detailTotal = detail.addRow({
        buyer_name: "Total",
        total_ci: { formula: rows.length ? `SUBTOTAL(109,D${firstDataRow}:D${lastDataRow})` : "0", result: totalRevenue },
    });

    detailTotal.font = { bold: true };

    const revenueFormula = (criteria: RevenueCriterion[]): ExcelJS.CellFormulaValue => {
        if (!rows.length) return { formula: "0", result: 0 };

        const revenueRange = `'CF Aging Details'!$D$${firstDataRow}:$D$${lastDataRow}`;
        const argumentsList = criteria.map((criterion) => {
            // Escape Excel criteria wildcards so buyer names are matched literally.
            const value = criterion.value.replace(/~/g, "~~").replace(/\*/g, "~*").replace(/\?/g, "~?").replace(/"/g, '""');
            return `'CF Aging Details'!$${criterion.column}$${firstDataRow}:$${criterion.column}$${lastDataRow},"=${value}"`;
        });

        const result = rows.reduce((total, row) => {
            return criteria.every((criterion) => row[criterion.field] === criterion.value) ? total + Math.round((row.total_ci ?? 0) * 100) : total;
        }, 0) / 100;

        return { formula: `SUMIFS(${revenueRange},${argumentsList.join(",")})`, result };
    };

    const addGrandTotal = (worksheet: ExcelJS.Worksheet, numericColumns: number[]) => {
        const lastRow = worksheet.rowCount;
        const total = worksheet.addRow(["Grand Total"]);
        total.font = { bold: true };

        numericColumns.forEach((columnNumber) => {
            const column = worksheet.getColumn(columnNumber);
            total.getCell(columnNumber).value = {
                formula: lastRow >= firstDataRow ? `SUBTOTAL(109,${column.letter}${firstDataRow}:${column.letter}${lastRow})` : "0",
                result: totalRevenue,
            };
        });
    };

    const chronologicalRows = [...rows].sort((left, right) => {
        return (left.calc_remit_date?.getTime() ?? Infinity) - (right.calc_remit_date?.getTime() ?? Infinity);
    });
    const months = [...new Set(chronologicalRows.map((row) => row.remit_month))];
    const weeks = [...new Set(chronologicalRows.map((row) => row.remit_week))];

    const addSummary = (name: string, title: string, labels: string[], field: RevenueCriterion["field"], column: RevenueCriterion["column"], headerLabel: string) => {
        const worksheet = createWorksheet(name, title, [{ key: "label", width: 28 }, { key: "revenue", width: 24 }], [headerLabel, "Sum of Revenue"]);
        worksheet.getColumn(2).numFmt = REVENUE_NUMBER_FORMAT;
        labels.forEach((value) => worksheet.addRow([value, revenueFormula([{ column, field, value }])]));
        addGrandTotal(worksheet, [2]);
    };

    addSummary("Monthly CF", "MONTH WISE CASH-FLOW INFO", months, "remit_month", "J", "Month");

    const monthlyWeekly = createWorksheet("Monthly Weekly CF", "MONTH WISE WEEK-WISE CASH-FLOW INFO", [
        { key: "remit_month", width: 24 },
        { key: "remit_week", width: 24 },
        { key: "revenue", width: 24 },
    ], ["Remit Month", "Remit Week", "Total"]);

    monthlyWeekly.getColumn(3).numFmt = REVENUE_NUMBER_FORMAT;

    months.forEach((month) => {
        const monthWeeks = weeks.filter((week) => rows.some((row) => row.remit_month === month && row.remit_week === week));
        monthWeeks.forEach((week, index) => {
            monthlyWeekly.addRow([index === 0 ? month : null, week, revenueFormula([
                { column: "J", field: "remit_month", value: month },
                { column: "I", field: "remit_week", value: week },
            ])]);
        });
    });
    addGrandTotal(monthlyWeekly, [3]);

    addSummary("Weekly CF", "WEEK WISE CASH-FLOW INFO", weeks, "remit_week", "I", "Week");

    addSummary("Aging", "AGING REPORT SUMMARY", agingSlabs.filter((slab) => rows.some((row) => row.aging_slab === slab)), "aging_slab", "L", "Aging Slab");

    const buyers = [...new Set(rows.map((row) => row.buyer_name))].sort((left, right) => left.localeCompare(right));
    const addBuyerSummary = (name: string, title: string, periods: string[], field: "remit_week" | "remit_month", column: "I" | "J") => {
        const columns = [
            { key: "buyer_name", width: 28 },
            ...periods.map((_, index) => ({ key: `period_${index}`, width: 20 })),
            { key: "total", width: 24 },
        ];

        const worksheet = createWorksheet(name, title, columns, ["Buyer", ...periods, "Grand Total"]);

        for (let index = 2; index <= columns.length; index++) {
            worksheet.getColumn(index).numFmt = REVENUE_NUMBER_FORMAT;
        }
        
        buyers.forEach((buyer) => {
            const buyerCriterion: RevenueCriterion = { column: "A", field: "buyer_name", value: buyer };
            worksheet.addRow([
                buyer,
                ...periods.map((period) => revenueFormula([buyerCriterion, { column, field, value: period }])),
                revenueFormula([buyerCriterion]),
            ]);
        });

        const lastRow = worksheet.rowCount;
        const total = worksheet.addRow(["Grand Total"]);
        total.font = { bold: true };

        periods.forEach((period, index) => {
            const periodColumn = worksheet.getColumn(index + 2);
            total.getCell(index + 2).value = {
                formula: `SUBTOTAL(109,${periodColumn.letter}${firstDataRow}:${periodColumn.letter}${lastRow})`,
                result: revenueFormula([{ column, field, value: period }]).result,
            };
        });
        
        const totalColumn = worksheet.getColumn(columns.length);
        total.getCell(columns.length).value = {
            formula: buyers.length ? `SUBTOTAL(109,${totalColumn.letter}${firstDataRow}:${totalColumn.letter}${lastRow})` : "0",
            result: totalRevenue,
        };
    };

    addBuyerSummary("Week", "BUYER WISE WEEKLY CASH-FLOW INFO", weeks, "remit_week", "I");
    addBuyerSummary("Month", "BUYER WISE MONTHLY CASH-FLOW INFO", months, "remit_month", "J");

    workbook.worksheets.forEach((worksheet) => {
        worksheet.autoFilter = {
            from: { row: TABLE_HEADER_ROW, column: 1 },
            to: { row: Math.max(TABLE_HEADER_ROW, worksheet.rowCount - 1), column: worksheet.getRow(TABLE_HEADER_ROW).cellCount },
        };
        worksheet.eachRow((row) => {
            row.alignment = { vertical: "middle", wrapText: row.number === TABLE_HEADER_ROW };
        });
    });

    const buffer = await workbook.xlsx.writeBuffer();
    return await addCashflowCharts(workbook, buffer);
};
