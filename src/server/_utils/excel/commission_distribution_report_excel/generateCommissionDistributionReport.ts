import ExcelJS from "exceljs";
import { currentTime, formatDate } from "~/utils/localDateString";
import { DOLLAR_SIGN_NUMBER_FORMAT, TABLE_HEADER_ROW, TEXT_FORMAT } from "../config";

const TABLE_COLUMN_COUNT = 8;

const tableColumns = [
    { key: "buyer_name", width: 28 },
    { key: "rdl_value", width: 18 },
    { key: "factory_value", width: 18 },
    { key: "commission", width: 18 },
    { key: "other_commission", width: 20 },
    { key: "overseas_commission", width: 22 },
    { key: "dhaka_commission", width: 20 },
    { key: "total_commission", width: 20 },
]

const tableHeader = [
    'Buyer Name',
    'Company Value',
    'Factory Value',
    'Commission',
    'Other Commission',
    'Overseas Commission',
    'Dhaka Commission',
    'Total Commission',
]

type CommissionDistributionRow = {
    buyer_name: string;
    rdl_value: unknown;
    factory_value: unknown;
    other_commission: unknown;
    overseas_commission: unknown;
    dhaka_commission: unknown;
};

type Props = {
    rows: CommissionDistributionRow[];
    fromDate: string;
    toDate: string;
    generatedBy: string;
};

export const generateCommissionDistributionReportExcel = async (props: Props) => {
    const { rows, fromDate, toDate, generatedBy } = props;

    const workbook = new ExcelJS.Workbook();

    // Set file metadata
    workbook.creator = generatedBy; 
    workbook.created = new Date();
    workbook.company = "Nex-Sourcify";
    workbook.subject = "Post-Exfactory Commercial Activity Report";
    workbook.title = "Post-Exfactory Commercial Activity Report";
    workbook.category = "Commercial Reports";
    workbook.manager = "Nexus ERP";

    const worksheet = workbook.addWorksheet("Commission Report", {
        views: [
            {
                state: "frozen",
                ySplit: TABLE_HEADER_ROW,
            },
        ],
    });

    worksheet.columns = tableColumns;

    worksheet.mergeCells(1, 1, 1, 6);
    worksheet.mergeCells(2, 1, 2, 2);
    worksheet.mergeCells(3, 1, 3, 2);
    worksheet.mergeCells(4, 1, 4, 2);

    worksheet.getCell("A1").value = `Commission Report`;
    worksheet.getCell("A2").value = `Date Range: ${formatDate(fromDate)} to ${formatDate(toDate)}`;
    worksheet.getCell("A3").value = `Generated by: ${generatedBy}`;
    worksheet.getCell("A4").value = `Generated on: ${formatDate(new Date())} at ${currentTime}`;

    worksheet.getRow(1).font = {
        bold: true,
        size: 20,
        color: { argb: "FF1F1F1F" },
    };

    worksheet.getRow(2).font = {
        size: 11,
        color: { argb: "FF4B4B4B" },
    };

    worksheet.getRow(3).font = {
        size: 11,
        color: { argb: "FF4B4B4B" },
    };

    worksheet.getRow(4).font = {
        size: 11,
        color: { argb: "FF4B4B4B" },
    };

    worksheet.getRow(6).font = {
        bold: true,
        color: { argb: "FFFFFFFF" },
    };
    
    worksheet.getRow(6).fill = {
        type: "pattern",
        pattern: "solid",
        fgColor: { argb: "1F4E78" },
    };

    worksheet.getRow(TABLE_HEADER_ROW).values = [...tableHeader];
    
    worksheet.autoFilter = {
        from: "A6",
        to: "AC6",
    };

    worksheet.getRow(1).height = 22;
    worksheet.getRow(2).height = 18;
    worksheet.getRow(3).height = 18;
    worksheet.getRow(6).height = 20;
    
    rows.forEach((row) => {
        const dataRowNumber = worksheet.rowCount + 1;
        const dataRow = worksheet.addRow({
            buyer_name: row.buyer_name,
            rdl_value: row.rdl_value,
            factory_value: row.factory_value,
            commission: { formula: `B${dataRowNumber} - C${dataRowNumber}` },
            other_commission: row.other_commission,
            overseas_commission: row.overseas_commission,
            dhaka_commission: row.dhaka_commission,
            total_commission: { formula: `E${dataRowNumber} + F${dataRowNumber} + G${dataRowNumber}` },
        });

        dataRow.getCell("D").numFmt = DOLLAR_SIGN_NUMBER_FORMAT;
        dataRow.getCell("H").numFmt = DOLLAR_SIGN_NUMBER_FORMAT;
    });

    // Remove borders from the first 4 rows and all columns
    for (let row = 1; row <= 5; row++) {
        for (let col = 1; col <= TABLE_COLUMN_COUNT; col++) {
            const cell = worksheet.getCell(row, col);
            cell.fill = {
                type: "pattern",
                pattern: "solid",
                fgColor: { argb: "FFFFFF" },
            };
        }
    }

    // Currency columns
    ["B", "C", "D", "E", "F", "G", "H"].forEach((col) => {
        worksheet.getColumn(col).numFmt = DOLLAR_SIGN_NUMBER_FORMAT;
    });

    ["A"].forEach((col) => {
        worksheet.getColumn(col).numFmt = TEXT_FORMAT;
    });

    const totalCommissionRow = worksheet.addRow({
        buyer_name: "Total",
        rdl_value: { formula: `SUBTOTAL(109,B${TABLE_HEADER_ROW + 1}:B${worksheet.rowCount})` },
        factory_value: { formula: `SUBTOTAL(109,C${TABLE_HEADER_ROW + 1}:C${worksheet.rowCount})` },
        commission: { formula: `SUBTOTAL(109,D${TABLE_HEADER_ROW + 1}:D${worksheet.rowCount})` },
        other_commission: { formula: `SUBTOTAL(109,E${TABLE_HEADER_ROW + 1}:E${worksheet.rowCount})` },
        overseas_commission: { formula: `SUBTOTAL(109,F${TABLE_HEADER_ROW + 1}:F${worksheet.rowCount})` },
        dhaka_commission: { formula: `SUBTOTAL(109,G${TABLE_HEADER_ROW + 1}:G${worksheet.rowCount})` },
        total_commission: { formula: `SUBTOTAL(109,H${TABLE_HEADER_ROW + 1}:H${worksheet.rowCount})` },
    });

    totalCommissionRow.font = {
        bold: true,
    };

    worksheet.eachRow((row) => {
        row.alignment = {
            vertical: "middle",
            wrapText: false,
        };
    });

    return await workbook.xlsx.writeBuffer();
};