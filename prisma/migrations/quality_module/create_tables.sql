DROP TABLE ORDER_CHECKLIST;

CREATE TABLE ORDER_CHECKLIST (
    ID UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
    BUYER_ID INT NOT NULL REFERENCES BUYERS(ID) ON DELETE RESTRICT,
    ORDER_ID UUID NOT NULL REFERENCES BUYER_ORDERS(ID) ON DELETE RESTRICT,
    STYLE_ID UUID NOT NULL REFERENCES ORDER_STYLES(ID) ON DELETE RESTRICT,
    SHIPMENT_ID UUID NOT NULL REFERENCES SHIPMENT_DETAILS(ID) ON DELETE RESTRICT,
    ADDED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

DROP TABLE ORDER_CHECKLIST_HISTORY;

CREATE TABLE ORDER_CHECKLIST_HISTORY (
    ID UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
    ORDER_CHECKLIST_ID UUID,
    BUYER_ID INT,
    ORDER_ID UUID,
    STYLE_ID UUID,
    SHIPMENT_ID UUID,
    action_type actions,
    action_by UUID NOT NULL REFERENCES USERS(ID) ON DELETE RESTRICT,
    ACTION_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ORDER_CHECKLIST_DETAILS (
    ID UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
    ORDER_CHECKLIST_ID UUID NOT NULL REFERENCES ORDER_CHECKLIST(ID) ON DELETE RESTRICT,
    SERIAL_NO INT NOT NULL,
    DOCUMENT_DETAILS TEXT NOT NULL,
    TECHNICAL_CHECK BOOLEAN DEFAULT FALSE,
    TECHNICAL_REMARKS TEXT,
    TECHNICAL_CHECK_DATE DATE,
    QA_CHECK BOOLEAN DEFAULT FALSE,
    QA_REMARKS TEXT,
    QA_CHECK_DATE DATE,
    ADDED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ORDER_CHECKLIST_DETAILS_HISTORY (
    ID UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
    ORDER_CHECKLIST_DETAILS_ID UUID REFERENCES ORDER_CHECKLIST_DETAILS(ID) ON DELETE RESTRICT,
    ORDER_CHECKLIST_ID UUID,
    SERIAL_NO INT,
    DOCUMENT_DETAILS TEXT,
    TECHNICAL_CHECK BOOLEAN DEFAULT FALSE,
    TECHNICAL_REMARKS TEXT,
    TECHNICAL_CHECK_DATE DATE,
    QA_CHECK BOOLEAN DEFAULT FALSE,
    QA_REMARKS TEXT,
    QA_CHECK_DATE DATE,
    action_type actions,
    action_by UUID NOT NULL REFERENCES USERS(ID) ON DELETE RESTRICT,
    ACTION_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);